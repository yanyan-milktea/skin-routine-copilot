// Usage:
//   node scripts/rag/eval-report.ts          write reports/retrieval-eval.md, reports/threshold-grid.md, reports/baseline.json
//   node scripts/rag/eval-report.ts --check  fail if the checked-in reports differ from a fresh run
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PHASE1_RETRIEVAL_CONFIG, validateRetrievalConfig } from "../../lib/ingredient-retrieval.ts";
import { baselineOf, loadCases, retrievalGateResults, runRetrievalEvals } from "./evals.ts";
import type { EvalReport } from "./evals.ts";
import { PATHS } from "./shared.ts";

const REPORT_DIR = join(PATHS.evalRoot, "reports");
const VECTOR_GRID = [0.52, 0.55, 0.58, 0.6, 0.62, 0.65, 0.68, 0.7];
const LEXICAL_GRID = [3.5, 4, 4.5, 5, 5.5, 6, 7, 8];
/** Evidence-precision constraint (design Section 5.2, added 2026-11-08). */
const MAX_IRRELEVANT_EVIDENCE_RATE = 0.02;

function evalMarkdown(report: EvalReport): string {
  const gates = retrievalGateResults(report);
  const lines = [
    "# Ingredient RAG retrieval eval (synthetic, keyless)",
    "",
    "Generated by `node scripts/rag/eval-report.ts`. Do not edit by hand.",
    "",
    "> Every number below comes from the **synthetic retrieval corpus** and the fixture-only",
    "> `synthetic-concept-embedding-v1` embedder. It verifies retrieval *mechanics* (gates, RRF,",
    "> abstention, deny list, lexical-only fallback). It is **not** evidence of how",
    "> `gemini-embedding-2` will rank real FDA/AAD passages, and it cannot calibrate the 0.62 / 6.0",
    "> answer thresholds for production.",
    "",
    "## Versions",
    "",
    ...Object.entries(report.versions).map(([key, value]) => `- ${key}: \`${value}\``),
    "",
    "## Dataset",
    "",
    `- Cases: ${report.dataset.cases} (adversarial share ${report.dataset.adversarial_share}, abstention share ${report.dataset.abstention_share})`,
    ...Object.entries(report.dataset.by_category).map(([key, value]) => `- ${key}: ${value}`),
    "",
    "## Milestone 1 retrieval gates",
    "",
    "| Gate | Kind | Threshold | Actual | Result |",
    "| --- | --- | --- | --- | --- |",
    ...gates.map((gate) => `| ${gate.gate} | ${gate.kind} | ${gate.threshold} | ${gate.actual} | ${gate.pass ? "pass" : "**fail**"} |`),
    "",
    "## Retrieval metrics",
    "",
    `- Recall@1 / @3 / @5: ${report.retrieval.recall_at_1} / ${report.retrieval.recall_at_3} / ${report.retrieval.recall_at_5}`,
    `- MRR: ${report.retrieval.mrr}; nDCG@5: ${report.retrieval.ndcg_at_5}`,
    `- Abstention accuracy: ${report.abstention.accuracy} (${report.abstention.abstained}/${report.abstention.must_abstain_cases})`,
    `- Status accuracy: ${report.status_accuracy}`,
    `- Cases with an irrelevant in-class chunk in evidence: ${report.precision.irrelevant_evidence_case_ids.join(", ") || "none"}`,
    "",
    "## Failing cases",
    "",
    ...(report.failures.length ? report.failures.map((failure) => `- \`${failure.case_id}\` (${failure.category}, status ${failure.status}): ${failure.failures.join("; ")}`) : ["None."]),
    "",
  ];
  return lines.join("\n");
}

async function gridMarkdown(): Promise<string> {
  const cases = loadCases();
  const rows: string[] = [];
  let best: { vector: number; lexical: number; recall: number } | null = null;
  for (const vector of VECTOR_GRID) {
    for (const lexical of LEXICAL_GRID) {
      const config = validateRetrievalConfig({ ...PHASE1_RETRIEVAL_CONFIG, tie_breakers: [...PHASE1_RETRIEVAL_CONFIG.tie_breakers], vector_answer_min_cosine: vector, lexical_answer_min_bm25: lexical }, { calibrationOverride: true });
      const report = await runRetrievalEvals({ config, cases });
      const irrelevantRate = report.precision.cases_with_irrelevant_evidence / Math.max(report.precision.cases_with_evidence, 1);
      const admissible = report.abstention.critical_false_eligible === 0 && report.abstention.out_of_scope_abstention >= 0.95 && report.abstention.false_eligible_rate <= 0.02 && irrelevantRate <= MAX_IRRELEVANT_EVIDENCE_RATE;
      if (admissible && (!best || report.retrieval.recall_at_5 > best.recall)) best = { vector, lexical, recall: report.retrieval.recall_at_5 };
      const fixed = vector === PHASE1_RETRIEVAL_CONFIG.vector_answer_min_cosine && lexical === PHASE1_RETRIEVAL_CONFIG.lexical_answer_min_bm25;
      rows.push(`| ${fixed ? `**${vector}**` : vector} | ${fixed ? `**${lexical}**` : lexical} | ${report.retrieval.recall_at_5} | ${report.abstention.critical_false_eligible} | ${report.abstention.out_of_scope_abstention} | ${report.abstention.false_eligible_rate} | ${report.precision.cases_with_irrelevant_evidence} | ${admissible ? "yes" : "no"} |`);
    }
  }
  return [
    "# Predeclared threshold grid (synthetic, informational only)",
    "",
    "Generated by `node scripts/rag/eval-report.ts`. Do not edit by hand.",
    "",
    "Objective (design Section 5.2): maximize Recall@5 subject to zero critical false-eligible",
    "cases, out-of-scope abstention >= 0.95, overall false-eligible rate <= 0.02, and at most",
    "2% of evidence-bearing cases containing a reviewer-labelled irrelevant chunk. The fixed",
    "Phase 1 constants are in bold. Runtime code cannot load any other values; this grid uses",
    "the offline-only calibration override.",
    "",
    "Because the vectors come from the fixture embedder, this grid **does not calibrate** the",
    "production thresholds. It shows how the gates behave on the synthetic corpus and gives the",
    "harness that a real `gemini-embedding-2` index will be run through.",
    "",
    `Best admissible cell on this fixture: vector ${best?.vector}, lexical ${best?.lexical} (Recall@5 ${best?.recall}).`,
    "",
    "| vector_answer_min_cosine | lexical_answer_min_bm25 | Recall@5 | Critical false-eligible | OOS abstention | False-eligible rate | Irrelevant-evidence cases | Admissible |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

const report = await runRetrievalEvals();
const outputs: Record<string, string> = {
  "retrieval-eval.md": evalMarkdown(report),
  "threshold-grid.md": await gridMarkdown(),
  "baseline.json": `${JSON.stringify(baselineOf(report), null, 2)}\n`,
};

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs).filter(([name, content]) => !existsSync(join(REPORT_DIR, name)) || readFileSync(join(REPORT_DIR, name), "utf8") !== content);
  if (stale.length) {
    console.error(`Stale eval reports: ${stale.map(([name]) => name).join(", ")}. Run: node scripts/rag/eval-report.ts`);
    process.exit(1);
  }
  console.log("Eval reports are current.");
} else {
  mkdirSync(REPORT_DIR, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) writeFileSync(join(REPORT_DIR, name), content);
  for (const gate of retrievalGateResults(report)) console.log(`${gate.pass ? "PASS" : "FAIL"} [${gate.kind}] ${gate.gate}: ${gate.actual}`);
}
